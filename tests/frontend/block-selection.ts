import assert from 'node:assert/strict';
import { Editor } from '@tiptap/core';
import StarterKit from '@tiptap/starter-kit';
import { undo, redo, history } from '@tiptap/pm/history';
import { ToggleHeading } from '../../frontend/src/ToggleHeading';
import { FileBlock, ResizableImage } from '../../frontend/src/nodes';
import { BlockSelection, createBlockSelectionPlugin, blockSelectionKey, selectedBlocks, rectangleBlocks } from '../../frontend/src/block-selection';
import { BLOCK_SELECTION_META, blockRoots, moveBlocks, movableBlocks } from '../../frontend/src/block-moving';
const p=(text:string)=>({type:'paragraph',content:[{type:'text',text,marks:[{type:'bold'}]}]});
const section={type:'toggleHeading',content:[{type:'heading',attrs:{level:2},content:[{type:'text',text:'Section'}]},p('Inside A'),p('Inside B')]};
const file={type:'fileBlock',attrs:{fileId:'keep-file',name:'Report.pdf',mode:'pdf'}};
const image={type:'image',attrs:{fileId:'keep-image',src:'media.php?id=keep-image',width:47,align:'right',alt:'Keep alt'}};
const editor=new Editor({element:null,extensions:[StarterKit,ToggleHeading,FileBlock,ResizableImage,BlockSelection],content:{type:'doc',content:[p('A'),p('B'),section,p('C'),file,image,p('End')]}});
const withPlugins=(ed:Editor)=>ed.state.reconfigure({plugins:[...ed.state.plugins,history(),createBlockSelectionPlugin()]});
let state=withPlugins(editor), checks=0;
const pos=(text:string)=>movableBlocks(state.doc).find(b=>b.node.textContent===text)!.pos;
const where=(name:string)=>movableBlocks(state.doc).find(b=>b.node.type.name===name)!;
const move=(positions:number[],to:number)=>{const tr=moveBlocks(state,positions,to);assert.ok(tr);state=state.apply(tr!);state.doc.check();checks++;};
const original=state.doc.toJSON();
move([pos('B'),pos('A')],state.doc.content.size);
assert.deepEqual(state.doc.toJSON().content.slice(-2),[p('A'),p('B')]);checks++;
assert.equal(selectedBlocks(state).length,2);checks++;
assert.ok(undo(state,tr=>{state=state.apply(tr)}));assert.deepEqual(state.doc.toJSON(),original);checks++;
assert.ok(redo(state,tr=>{state=state.apply(tr)}));assert.deepEqual(state.doc.toJSON().content.slice(-2),[p('A'),p('B')]);checks++;
let toggle=where('toggleHeading');move([pos('A'),pos('B')],toggle.pos+1+toggle.node.firstChild!.nodeSize);
toggle=where('toggleHeading');assert.deepEqual([toggle.node.child(1).textContent,toggle.node.child(2).textContent],['A','B']);checks++;
move([pos('A'),pos('B'),pos('Inside A'),pos('Inside B')],state.doc.content.size);
toggle=where('toggleHeading');assert.equal(toggle.node.childCount,2);assert.equal(toggle.node.lastChild!.textContent,'');checks++;
assert.deepEqual(state.doc.toJSON().content.slice(-4),[p('A'),p('B'),p('Inside A'),p('Inside B')]);checks++;
const beforeFile=where('fileBlock').node.toJSON(),beforeImage=where('image').node.toJSON();
move([where('fileBlock').pos,where('image').pos],0);
assert.deepEqual(state.doc.firstChild!.toJSON(),beforeFile);assert.deepEqual(state.doc.child(1).toJSON(),beforeImage);checks++;
// Non-contiguous roots from multiple parents preserve their original document order.
move([pos('C'),pos('Inside B')],0);assert.equal(state.doc.child(0).textContent,'C');assert.equal(state.doc.child(1).textContent,'Inside B');checks++;
assert.equal(moveBlocks(state,[],0),null);checks++;
assert.equal(moveBlocks(state,[pos('A')],-1),null);checks++;
assert.equal(moveBlocks(state,[pos('A')],state.doc.content.size+1),null);checks++;
toggle=where('toggleHeading');assert.equal(moveBlocks(state,[toggle.pos,pos('A')],toggle.pos+2),null);checks++;
const nestedEditor=new Editor({element:null,extensions:[StarterKit,ToggleHeading,BlockSelection],content:{type:'doc',content:[section,p('Other')]}});state=withPlugins(nestedEditor);
toggle=where('toggleHeading');assert.deepEqual(blockRoots(state.doc,[toggle.pos,pos('Inside A'),pos('Inside B')]).map(b=>b.pos),[toggle.pos]);checks++;
assert.deepEqual(blockRoots(state.doc,[toggle.pos+1]).map(b=>b.pos),[]);checks++;
move([toggle.pos,pos('Inside A')],state.doc.content.size);assert.equal(state.doc.lastChild!.type.name,'toggleHeading');assert.equal(state.doc.lastChild!.childCount,3);checks++;
// Selection is transient plugin state, never persisted in page JSON.
const a=pos('Inside A'),b=pos('Inside B');state=state.apply(state.tr.setMeta(BLOCK_SELECTION_META,[a,b]));assert.deepEqual(selectedBlocks(state),[a,b]);checks++;
assert.equal(JSON.stringify(state.doc.toJSON()).includes('feuillet-block-selected'),false);checks++;
const plugin=state.plugins.find(p=>p.spec.key===blockSelectionKey)!;
const decorations=plugin.props.decorations!(state) as any;assert.equal(decorations.find().length,2);checks++;
state=state.apply(state.tr.insertText('prefix ',a+1));assert.equal(selectedBlocks(state).length,2);checks++;
state=state.apply(state.tr.setMeta(BLOCK_SELECTION_META,[]));assert.deepEqual(selectedBlocks(state),[]);checks++;
const rect=(top:number,bottom:number,left=100,right=500)=>({top,bottom,left,right});
const boxes=[{pos:0,end:5,rect:rect(100,130)},{pos:5,end:40,rect:rect(140,300),header:rect(140,170)},{pos:15,end:25,rect:rect(180,210,125)},{pos:25,end:35,rect:rect(220,250,125)},{pos:40,end:45,rect:rect(310,340)}];
assert.deepEqual(rectangleBlocks(rect(99,135,20,400),boxes),[0]);checks++;
assert.deepEqual(rectangleBlocks(rect(120,160,20,400),boxes),[0,5]);checks++;
assert.deepEqual(rectangleBlocks(rect(175,245,20,400),boxes),[15,25]);checks++;
assert.deepEqual(rectangleBlocks(rect(135,305,20,400),boxes),[5]);checks++;
assert.deepEqual(rectangleBlocks(rect(171,299,600,650),boxes),[]);checks++;
assert.deepEqual(rectangleBlocks(rect(145,240,20,400),boxes),[5]);checks++;
assert.deepEqual(rectangleBlocks(rect(280,330,20,400),boxes),[5,40]);checks++;
// A drag cannot merge into the immediately preceding typing history event.
state=withPlugins(editor);state=state.apply(state.tr.insertText('Typed ',1));
const beforeMove=state.doc.toJSON();move([pos('Typed A'),pos('B')],state.doc.content.size);
assert.ok(undo(state,tr=>{state=state.apply(tr)}));assert.deepEqual(state.doc.toJSON(),beforeMove);checks++;
console.log(`${checks}/${checks} group selection and atomic multi-block move checks passed`);
