import assert from 'node:assert/strict';
import { notebookHomePages } from '../../frontend/src/notebook-home';
import type { Page } from '../../frontend/src/types';
const make = (id:string, patch:Partial<Page>):Page => ({id, title:id, space_id:'a', visibility:'private', description:'', tags:[], updated_at:'2026-10-14', ...patch} as Page);
const pages = [make('old',{title:'Été à préparer',category_id:'ideas'}),make('child',{title:'Une sous-page',parent_id:'old',visibility:'public',updated_at:'2026-10-15'}),make('secret',{title:'Été à préparer',space_id:'b',updated_at:'2026-10-16',category_id:'ideas'}),make('tagged',{title:'Archives',tags:['café'],description:'Séjour utile',updated_at:undefined,created_at:'2026-10-13'})];
const before=JSON.stringify(pages);
assert.deepEqual(notebookHomePages(pages,'a').map(p=>p.id),['child','old','tagged']);
assert.deepEqual(notebookHomePages(pages,'b').map(p=>p.id),['secret']);
assert.deepEqual(notebookHomePages(pages,'a','ideas').map(p=>p.id),['old']);
assert.deepEqual(notebookHomePages(pages,'a','','ete preparer').map(p=>p.id),['old']);
assert.deepEqual(notebookHomePages(pages,'a','','CAFE sejour').map(p=>p.id),['tagged']);
assert.deepEqual(notebookHomePages(pages,'a','ideas','sous-page'),[]);
assert.deepEqual(notebookHomePages(pages,'unknown'),[]);
assert.equal(notebookHomePages(pages).length,4);
assert.equal(notebookHomePages(pages,'a')[0].visibility,'public');
assert.ok(notebookHomePages(pages,'a').some(p=>p.visibility==='private'));
assert.equal(JSON.stringify(pages),before);
assert.deepEqual(notebookHomePages([make('z',{title:'Idée'}),make('a',{title:'Idée'})],'a').map(p=>p.id),['a','z']);
console.log('12/12 notebook home checks passed: scope, private/public subpages, category/search combinations, accent-insensitive metadata, stable order and immutable input');
