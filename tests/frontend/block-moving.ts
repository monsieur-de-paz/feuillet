import assert from 'node:assert/strict';
import { Editor } from '@tiptap/core';
import StarterKit from '@tiptap/starter-kit';
import { ToggleHeading } from '../../frontend/src/ToggleHeading';
import { MapBlock } from '../../frontend/src/MapBlock';
import { FileBlock, ResizableImage } from '../../frontend/src/nodes';
import { moveBlock, movableBlocks } from '../../frontend/src/block-moving';
const p=(text:string)=>({type:'paragraph',content:[{type:'text',text,marks:[{type:'bold'}]}]});
const toggle={type:'toggleHeading',content:[{type:'heading',attrs:{level:2},content:[{type:'text',text:'Section'}]},p('Dedans')]};
const editor=new Editor({element:null,extensions:[StarterKit,ToggleHeading,FileBlock],content:{type:'doc',content:[p('A'),p('B'),toggle,p('C'),{type:'fileBlock',attrs:{fileId:'kept-id',name:'Cours.pdf',mode:'pdf'}}]}});
let state=editor.state,checks=0;
function move(from:number,to:number){const tr=moveBlock(state,from,to);assert.ok(tr);state=state.apply(tr!);state.doc.check();checks++;}
let blocks=movableBlocks(state.doc);assert.ok(!blocks.some(b=>b.node.type.name==='heading'));checks++;
const a=state.doc.child(0),b=state.doc.child(1);move(0,a.nodeSize+b.nodeSize);assert.equal(state.doc.child(1).textContent,'A');checks++;
let section=movableBlocks(state.doc).find(b=>b.node.type.name==='toggleHeading')!;
let from=movableBlocks(state.doc).find(b=>b.node.textContent==='A')!.pos;
move(from,section.pos+1+section.node.firstChild!.nodeSize);
section=movableBlocks(state.doc).find(b=>b.node.type.name==='toggleHeading')!;
assert.equal(section.node.child(1).textContent,'A');checks++;
from=movableBlocks(state.doc).find(b=>b.node.textContent==='Dedans')!.pos;
move(from,section.pos+section.node.nodeSize);assert.ok(state.doc.textContent.includes('Dedans'));checks++;
section=movableBlocks(state.doc).find(b=>b.node.type.name==='toggleHeading')!;from=movableBlocks(state.doc).find(b=>b.node.textContent==='A')!.pos;
move(from,state.doc.content.size);section=movableBlocks(state.doc).find(b=>b.node.type.name==='toggleHeading')!;
assert.equal(section.node.childCount,2);assert.equal(section.node.child(1).type.name,'paragraph');checks++;
assert.equal(state.doc.lastChild!.firstChild!.marks[0].type.name,'bold');checks++;
let file=movableBlocks(state.doc).find(b=>b.node.type.name==='fileBlock')!;const json=file.node.toJSON();move(file.pos,0);assert.deepEqual(state.doc.firstChild!.toJSON(),json);checks++;
section=movableBlocks(state.doc).find(b=>b.node.type.name==='toggleHeading')!;
assert.equal(moveBlock(state,section.pos,section.pos+2),null);checks++;
assert.equal(moveBlock(state,section.pos+1,state.doc.content.size),null);checks++;
assert.equal(moveBlock(state,0,-1),null);checks++;
assert.equal(moveBlock(state,0,state.doc.content.size+10),null);checks++;
assert.equal(moveBlock(state,0,0),null);checks++;
const nested={type:'doc',content:[{type:'toggleHeading',content:[{type:'heading',attrs:{level:1}},toggle]},p('End')]};
const nestedEditor=new Editor({element:null,extensions:[StarterKit,ToggleHeading],content:nested});state=nestedEditor.state;
const inner=movableBlocks(state.doc).filter(b=>b.node.type.name==='toggleHeading').at(-1)!;move(inner.pos,state.doc.content.size);assert.equal(state.doc.lastChild!.type.name,'toggleHeading');checks++;
const mediaEditor=new Editor({element:null,extensions:[StarterKit,ToggleHeading,ResizableImage,MapBlock],content:{type:'doc',content:[{type:'image',attrs:{fileId:'kept-image',src:'media.php?id=kept-image',width:37,align:'right',alt:'Image intacte'}},toggle,{type:'mapBlock',attrs:{address:'Toulouse',embedUrl:''}}]}});
state=mediaEditor.state;
const imageBefore=state.doc.firstChild!.toJSON();
let targetSection=movableBlocks(state.doc).find(b=>b.node.type.name==='toggleHeading')!;
move(0,targetSection.pos+1+targetSection.node.firstChild!.nodeSize);
targetSection=movableBlocks(state.doc).find(b=>b.node.type.name==='toggleHeading')!;
assert.deepEqual(targetSection.node.child(1).toJSON(),imageBefore);checks++;
let imagePos=movableBlocks(state.doc).find(b=>b.node.type.name==='image')!.pos;move(imagePos,state.doc.content.size);
assert.deepEqual(state.doc.lastChild!.toJSON(),imageBefore);checks++;
const map=movableBlocks(state.doc).find(b=>b.node.type.name==='mapBlock')!;const mapBefore=map.node.toJSON();move(map.pos,0);assert.deepEqual(state.doc.firstChild!.toJSON(),mapBefore);checks++;
console.log(`${checks}/${checks} atomic block move checks passed`);
